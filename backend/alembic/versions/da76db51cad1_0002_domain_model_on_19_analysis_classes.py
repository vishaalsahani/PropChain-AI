    legacy_transfer_dates = {
        row[0]: row[1] for row in bind.execute(sa.text("SELECT id, transfer_date FROM ownership_records"))
    }

    op.rename_table("ownership_records", "ownership_nodes")
    with op.batch_alter_table("ownership_nodes", recreate="always") as batch_op:
        batch_op.alter_column("to_party", new_column_name="person_name", existing_type=sa.String(length=255), existing_nullable=False)
        batch_op.alter_column("transfer_type", new_column_name="transaction_type", existing_type=sa.String(length=100), existing_nullable=False)
        batch_op.add_column(sa.Column("transaction_date", sa.String(length=50), nullable=False, server_default=""))
        batch_op.drop_column("from_party")
        batch_op.drop_column("transfer_date")
        batch_op.drop_column("document_id")
        batch_op.drop_column("gap_flag")
        batch_op.drop_column("analysis_run_id")
        batch_op.drop_column("confidence")
        batch_op.drop_column("evidence")
        batch_op.drop_column("created_at")
        batch_op.drop_index("ix_ownership_records_id")
        batch_op.create_index("ix_ownership_nodes_id", ["id"], unique=False)

    for row_id, transfer_date in legacy_transfer_dates.items():
        value = ""
        if transfer_date is not None:
            value = transfer_date.isoformat() if hasattr(transfer_date, "isoformat") else str(transfer_date)[:10]
        bind.execute(sa.text("UPDATE ownership_nodes SET transaction_date = :v WHERE id = :i"), {"v": value, "i": row_id})

    # -------------------------------------------------------------- documents
    with op.batch_alter_table("documents", recreate="always") as batch_op:
        batch_op.alter_column("status", type_=sa.String(length=10), existing_nullable=False)
        batch_op.drop_column("language")
        batch_op.drop_column("page_count")
        batch_op.drop_column("content_type")
        batch_op.drop_column("doc_type_confidence")
        batch_op.drop_column("ocr_text")
        batch_op.drop_column("version")
        batch_op.drop_column("uploaded_by")

    # ------------------------------------------------------------- properties
    # Explicit rebuild, not batch reflection: SQLite reflection carries CHECK
    # constraints into a rebuilt table, and ck_properties_areaunit references the
    # area_unit column being dropped here (alembic's documented batch limitation).
    op.create_table(
        "properties_old",
        sa.Column("id", sa.Integer(), nullable=False),
        sa.Column("owner_id", sa.Integer(), nullable=False),
        sa.Column("title", sa.String(length=255), nullable=False),
        sa.Column("state", sa.String(length=100), nullable=False),
        sa.Column("district", sa.String(length=100), nullable=False),
        sa.Column("taluka", sa.String(length=100), nullable=False),
        sa.Column("village", sa.String(length=100), nullable=False),
        sa.Column("survey_number", sa.String(length=100), nullable=False),
        sa.Column("gat_number", sa.String(length=100), nullable=False),
        sa.Column("cts_number", sa.String(length=100), nullable=False),
        sa.Column("area_sqft", sa.Float(), nullable=True),
        sa.Column("status", sa.String(length=50), nullable=False),
        sa.Column("risk_score", sa.Float(), nullable=True),
        sa.Column("created_at", sa.DateTime(), nullable=False),
        sa.ForeignKeyConstraint(["owner_id"], ["users.id"], name=op.f("fk_properties_owner_id_users")),
        sa.PrimaryKeyConstraint("id", name=op.f("pk_properties")),
    )
    op.execute(
        "INSERT INTO properties_old (id, owner_id, title, state, district, taluka, village, survey_number, gat_number, cts_number, area_sqft, status, risk_score, created_at) "
        "SELECT id, owner_id, title, state, district, taluka, village, survey_number, gat_number, cts_number, area_sqft, status, risk_score, created_at FROM properties"
    )
    op.drop_table("properties")
    op.rename_table("properties_old", "properties")
    op.create_index(op.f("ix_properties_id"), "properties", ["id"], unique=False)

    # ------------------------------------------------------------------ users
    with op.batch_alter_table("users", recreate="always") as batch_op:
        batch_op.alter_column(
            "role",
            type_=sa.Enum("buyer", "owner", "reviewer", "admin", name="userrole"),
            existing_nullable=False,
        )
        batch_op.drop_column("updated_at")

