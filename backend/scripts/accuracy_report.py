#!/usr/bin/env python
"""AC-2 accuracy harness: score the real pipeline against labelled fixtures.

Runs the actual engine chain (OCR -> classifier -> extractor) over every
fixture in the corpus generated by ``scripts/make_fixtures.py`` and scores the
extracted fields against the ground truth, then writes a markdown report
(default ``backend/artifacts/phase2_accuracy.md``).

Scoring rules (documented so the numbers are reproducible):

* names (owner/seller/buyer) and place names (village/taluka/district):
  fuzzy match >= 85 via ``app.services.normalize.name_similarity``
  (honorific/case/punctuation-insensitive);
* identifiers (survey/gat/cts/registration number): character equality after
  the same normalization the extractor uses;
* dates: ISO equality;
* area_sqft / consideration_amount: numeric match within 5% / 1%.

Usage (from ``backend``)::

    .venv\\Scripts\\python.exe scripts\\accuracy_report.py            # real engines from .env
    .venv\\Scripts\\python.exe scripts\\accuracy_report.py --fake     # smoke run on fake engines
    .venv\\Scripts\\python.exe scripts\\accuracy_report.py --limit 4  # quick subset
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

DEFAULT_FIXTURES = Path.home() / "AppData/Local/Temp/propchain_fixtures"
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "artifacts" / "phase2_accuracy.md"

# The script lives in backend/scripts, so `app` is not importable when it is run
# directly; add the backend directory before importing anything from the app.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.services import normalize  # noqa: E402  (stdlib-only module, no settings access)

#: AC-2 headline evidence fields (owner / survey / area / date) plus the other
#: canonical fields the fixtures label, scored per document.
CORE_FIELDS = ("owner_name", "survey_number", "area_sqft", "registration_date")
HEADLINE_FIELDS = (
    "owner_name", "seller_name", "buyer_name", "survey_number", "gat_number",
    "cts_number", "area_sqft", "registration_date", "registration_number",
    "consideration_amount", "village", "taluka", "district",
)

NAME_FIELDS = frozenset({"owner_name", "seller_name", "buyer_name",
                         "village", "taluka", "district"})
IDENT_FIELDS = frozenset({"survey_number", "gat_number", "cts_number"})
DATE_FIELDS = frozenset({"registration_date", "execution_date"})
NUMERIC_TOLERANCE = {"area_sqft": 0.05, "consideration_amount": 0.01}


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fixtures", default=str(DEFAULT_FIXTURES),
                        help="fixture directory written by scripts/make_fixtures.py")
    parser.add_argument("--out", default=str(DEFAULT_OUTPUT), help="markdown report path")
    parser.add_argument("--fake", action="store_true",
                        help="force the fake engines (smoke run; accuracy is meaningless)")
    parser.add_argument("--limit", type=int, default=0, help="score only the first N fixtures")
    return parser.parse_args(argv)


def score_field(field: str, expected, got) -> bool:
    """One comparison, using the same normalization the extractor emits."""
    if got is None:
        return False
    if field in NUMERIC_TOLERANCE:
        try:
            expected_value, got_value = float(expected), float(got)
        except (TypeError, ValueError):
            return False
        tolerance = NUMERIC_TOLERANCE[field]
        if expected_value == 0:
            return abs(got_value) <= tolerance
        return abs(got_value - expected_value) / abs(expected_value) <= tolerance
    if field in NAME_FIELDS:
        return normalize.name_similarity(str(expected), str(got)) >= 85.0
    if field == "registration_number":
        return normalize.normalize_registration_number(str(expected)) == \
            normalize.normalize_registration_number(str(got))
    if field in IDENT_FIELDS:
        return normalize.normalize_identifier(str(expected)) == \
            normalize.normalize_identifier(str(got))
    if field in DATE_FIELDS:
        return str(expected)[:10] == str(got)[:10]
    # Fallback: case/whitespace-insensitive text equality.
    return normalize.normalize_whitespace(str(expected)).casefold() == \
        normalize.normalize_whitespace(str(got)).casefold()


def run_fixture(entry: dict, ocr_service, classifier, extractor) -> dict:
    """OCR -> classify -> extract one fixture and score it."""
    path = Path(entry["_dir"]) / entry["filename"]
    ocr_result = ocr_service.extract(str(path), ["marathi", "english"])
    page_text = "\f".join(page.text for page in ocr_result.pages)
    classification = classifier.classify(entry["filename"], page_text)
    candidates = extractor.extract(classification.doc_type, page_text)

    got: dict[str, str] = {}
    for candidate in candidates:
        value = candidate.normalized_value if candidate.normalized_value is not None \
            else candidate.raw_value
        if value is not None and candidate.field_name not in got:
            got[candidate.field_name] = value

    return {
        "filename": entry["filename"],
        "doc_type": entry["doc_type"],
        "language": entry["language"],
        "variant": entry["variant"],
        "predicted_doc_type": classification.doc_type,
        "classified_ok": classification.doc_type == entry["doc_type"],
        "ocr_language": ocr_result.language,
        "ocr_pages": len(ocr_result.pages),
        "ocr_engine": ocr_result.engine_version,
        "classifier_engine": classification.engine_version,
        "extractor_engine": extractor.engine_version,
        "expected": entry["expected"],
        "got": got,
        "results": {
            field: score_field(field, value, got.get(field))
            for field, value in entry["expected"].items()
            if field in HEADLINE_FIELDS
        },
        "extra_fields": sorted(set(got) - set(entry["expected"]) - {"currency"}),
        "notes": entry.get("notes", []),
    }


def aggregate(rows: list[dict], fields: tuple[str, ...]) -> tuple[int, int]:
    matched = total = 0
    for row in rows:
        for field in fields:
            if field in row["results"]:
                total += 1
                matched += 1 if row["results"][field] else 0
    return matched, total


def rate(matched: int, total: int) -> str:
    if total == 0:
        return "n/a"
    return f"{matched}/{total} ({100.0 * matched / total:.1f}%)"


def write_report(rows: list[dict], out_path: Path, fixtures_dir: Path,
                 engines: tuple[str, str, str], fake: bool) -> None:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    core_matched, core_total = aggregate(rows, CORE_FIELDS)
    head_matched, head_total = aggregate(rows, HEADLINE_FIELDS)
    classified_ok = sum(1 for row in rows if row["classified_ok"])

    lines: list[str] = []
    lines.append("# Phase 2 — AC-2 labelled-fixture accuracy report")
    lines.append("")
    lines.append(f"- Generated: {now}")
    lines.append(f"- Fixtures: `{fixtures_dir}` ({len(rows)} documents)")
    lines.append(f"- Engines: ocr=`{engines[0]}`, classifier=`{engines[1]}`, nlp=`{engines[2]}`")
    if fake:
        lines.append("- **--fake smoke run: accuracy numbers do not measure the real engines.**")
    lines.append("")
    lines.append("## Headline")
    lines.append("")
    lines.append(f"- Document classification: {rate(classified_ok, len(rows))}")
    lines.append(f"- AC-2 core fields (owner / survey / area / date): **{rate(core_matched, core_total)}**")
    lines.append(f"- All scored fields: {rate(head_matched, head_total)}")
    lines.append("")
    lines.append("## By language and variant")
    lines.append("")
    lines.append("| group | docs | classification | AC-2 core | all scored fields |")
    lines.append("|---|---|---|---|---|")
    groups: list[tuple[str, list[dict]]] = [
        ("English", [row for row in rows if row["language"] == "english"]),
        ("Marathi", [row for row in rows if row["language"] == "marathi"]),
        ("Digital (text layer)", [row for row in rows if row["variant"] == "digital"]),
        ("Scanned (image OCR)", [row for row in rows if row["variant"] == "scanned"]),
        ("All", rows),
    ]
    for name, group_rows in groups:
        if not group_rows:
            continue
        group_core = aggregate(group_rows, CORE_FIELDS)
        group_head = aggregate(group_rows, HEADLINE_FIELDS)
        group_ok = sum(1 for row in group_rows if row["classified_ok"])
        lines.append(
            f"| {name} | {len(group_rows)} | {rate(group_ok, len(group_rows))} "
            f"| {rate(*group_core)} | {rate(*group_head)} |"
        )
    lines.append("")
    lines.append("## Per document")
    lines.append("")
    for row in rows:
        lines.append(f"### `{row['filename']}`")
        lines.append("")
        lines.append(f"- Expected type `{row['doc_type']}` → predicted "
                     f"`{row['predicted_doc_type']}` "
                     f"({'OK' if row['classified_ok'] else 'MISMATCH'}); "
                     f"OCR language `{row['ocr_language']}`, pages {row['ocr_pages']}.")
        lines.append("")
        lines.append("| field | expected | extracted | match |")
        lines.append("|---|---|---|---|")
        for field in HEADLINE_FIELDS:
            if field not in row["expected"]:
                continue
            expected = row["expected"][field]
            got = row["got"].get(field, "—")
            mark = "✅" if row["results"][field] else "❌"
            lines.append(f"| `{field}` | {expected} | {got} | {mark} |")
        if row["extra_fields"]:
            lines.append("")
            lines.append(f"- Extra fields extracted (not scored): {', '.join(row['extra_fields'])}")
        for note in row["notes"]:
            lines.append(f"- Note: {note}")
        lines.append("")

    lines.append("## Limitations (honest list)")
    lines.append("")
    lines.append("- The fixture wording shares label conventions with the pattern packs, so this")
    lines.append("  corpus measures the end-to-end pipeline (render/scan → OCR → classify →")
    lines.append("  extract → normalize), not generalisation to unseen wording. The full AC")
    lines.append("  dataset with independent ground truth is Phase 10 work.")
    lines.append("- Names are compared fuzzily (≥85) because OCR of Devanagari names can differ")
    lines.append("  in one conjunct; identifiers and dates are compared exactly.")
    lines.append("- `area_sqft` tolerance is 5% to absorb digit-script rounding; the fixture")
    lines.append("  generator prints areas the normalizer can parse exactly.")
    lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")

    json_path = out_path.with_suffix(".json")
    json_path.write_text(
        json.dumps({"generated": now, "fake": fake, "rows": rows}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"report: {out_path}")
    print(f"data:   {json_path}")


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    if args.fake:
        os.environ["OCR_ENGINE"] = "fake"
        os.environ["DOC_CLASSIFIER_ENGINE"] = "fake"
        os.environ["NLP_EXTRACTOR_ENGINE"] = "fake"

    # Imported after engine selection so --fake wins over backend/.env.
    from app.services.registry import get_doc_classifier, get_nlp_extractor, get_ocr_service

    fixtures_dir = Path(args.fixtures)
    manifest_path = fixtures_dir / "_manifest.json"
    if not manifest_path.exists():
        print(f"manifest not found: {manifest_path}\n"
              f"run: .venv\\Scripts\\python.exe scripts\\make_fixtures.py", file=sys.stderr)
        return 2

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if args.limit:
        manifest = manifest[: args.limit]

    ocr_service = get_ocr_service()
    classifier = get_doc_classifier()
    extractor = get_nlp_extractor()
    engines = (ocr_service.engine_version, classifier.engine_version, extractor.engine_version)
    print(f"engines: {engines[0]} | {engines[1]} | {engines[2]}")

    rows: list[dict] = []
    failures = 0
    for number, entry in enumerate(manifest, start=1):
        entry["_dir"] = str(fixtures_dir)
        try:
            row = run_fixture(entry, ocr_service, classifier, extractor)
        except Exception as exc:  # keep scoring the rest of the corpus
            failures += 1
            print(f"  [{number:2}] {entry['filename']:40} ERROR: {exc}")
            continue
        rows.append(row)
        core = aggregate([row], CORE_FIELDS)
        print(f"  [{number:2}] {entry['filename']:40} "
              f"{'OK ' if row['classified_ok'] else 'MIS-CLS'} "
              f"core={rate(*core)}")

    if not rows:
        print("no fixtures scored", file=sys.stderr)
        return 1

    core_matched, core_total = aggregate(rows, CORE_FIELDS)
    head_matched, head_total = aggregate(rows, HEADLINE_FIELDS)
    classified_ok = sum(1 for row in rows if row["classified_ok"])
    print(f"\nclassification: {rate(classified_ok, len(rows))}")
    print(f"AC-2 core:      {rate(core_matched, core_total)}")
    print(f"all fields:     {rate(head_matched, head_total)}")
    if failures:
        print(f"document errors: {failures}")

    write_report(rows, Path(args.out), fixtures_dir, engines, args.fake)
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
