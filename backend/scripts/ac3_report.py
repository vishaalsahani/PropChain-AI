#!/usr/bin/env python
"""AC-3 seeded-error detection harness (Phase 3).

Runs the real pipeline over the case corpus generated by
``scripts/make_error_set.py`` — OCR -> classifier -> extractor (the configured
engines, same as production) followed by the consistency matrix, the ownership
builder, the Maharashtra rule pack and the verdict policy — and scores whether
each seeded inconsistency was flagged with a reason.

Scoring rules (documented so the numbers are reproducible):

* a case is **detected** when every rule ref listed in its manifest ``expect``
  appears among the run's findings (each finding carries title, severity,
  evidence and a recommended action);
* a **control** case (no seeded error) must produce *no findings at all* —
  a single finding is a false positive and fails the case;
* the verdict is scored separately when the manifest pins one.

Usage (from ``backend``)::

    .venv\\Scripts\\python.exe scripts\\ac3_report.py
    .venv\\Scripts\\python.exe scripts\\ac3_report.py --fake     # pipeline smoke only
    .venv\\Scripts\\python.exe scripts\\ac3_report.py --limit 4
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

DEFAULT_CASES = Path.home() / "AppData/Local/Temp/propchain_errorset"
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "artifacts" / "phase3_ac3.md"

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

#: AC-3 target from the review table: >=90% of seeded errors flagged with a reason.
TARGET_RATE = 0.90


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cases", default=str(DEFAULT_CASES),
                        help="case directory written by scripts/make_error_set.py")
    parser.add_argument("--out", default=str(DEFAULT_OUTPUT), help="markdown report path")
    parser.add_argument("--fake", action="store_true",
                        help="force the fake OCR/classifier/extractor (smoke run only)")
    parser.add_argument("--limit", type=int, default=0, help="score only the first N cases")
    return parser.parse_args(argv)


def run_case(entry: dict, case_dir: Path, ocr_service, classifier, extractor,
             validator, ownership_builder, rule_engine, derive_verdict, blob_builder) -> dict:
    """Pipeline + Phase-3 engines for one case; returns a scored result row."""
    extracted: dict[int, dict] = {}
    document_meta: dict[int, dict] = {}
    profile_documents: list[dict] = []

    for index, doc in enumerate(entry["documents"], start=1):
        path = case_dir / doc["filename"]
        ocr_result = ocr_service.extract(str(path), ["marathi", "english"])
        page_text = "\f".join(page.text for page in ocr_result.pages)
        classification = classifier.classify(doc["filename"], page_text)
        candidates = extractor.extract(classification.doc_type, page_text)
        payload = blob_builder(classification.doc_type, ocr_result.language, candidates)
        verified = entry.get("verified_override", {}).get(doc["filename"])

        extracted[index] = payload
        # Mirrors analysis_engine.run_property_analysis: the meta carries the
        # extracted blob plus the on-chain verification state.
        document_meta[index] = {
            "filename": doc["filename"],
            "doc_type": classification.doc_type,
            "language": ocr_result.language,
            "blockchain_verified": verified,
            "extracted": payload,
        }
        profile_documents.append(
            {
                "doc_id": index,
                "filename": doc["filename"],
                "doc_type": classification.doc_type,
                "blockchain_verified": verified,
            }
        )

    chain = ownership_builder.build(document_meta)
    flags = validator.validate(extracted, document_meta)
    profile = dict(entry["profile"])
    profile["documents"] = profile_documents
    profile["ownership"] = [
        {
            "from_party": node.from_party,
            "to_party": node.to_party,
            "transfer_type": node.transfer_type,
            "transfer_date": node.transfer_date,
            "document_ref": node.document_ref,
            "sequence": node.sequence,
            "gap_flag": node.gap_flag,
        }
        for node in chain
    ]
    flags += rule_engine.evaluate(profile, list(extracted.values()))
    outcome = derive_verdict(flags, chain, profile_documents)

    expected = list(entry["expect"].get("rule_refs") or [])
    observed = [flag.rule_ref for flag in flags if flag.rule_ref]
    missing = [ref for ref in expected if ref not in observed]
    detected = (not missing) if expected else not flags
    verdict_ok = None
    if entry["expect"].get("verdict"):
        verdict_ok = outcome.verdict == entry["expect"]["verdict"]

    return {
        "name": entry["name"],
        "case": entry["case"],
        "language": entry["language"],
        "injected": entry["injected"],
        "expected": expected,
        "observed": observed,
        "missing": missing,
        "detected": detected,
        "verdict": outcome.verdict,
        "verdict_expected": entry["expect"].get("verdict"),
        "verdict_ok": verdict_ok,
        "reasons": outcome.reasons,
        "not_checked": outcome.not_checked,
        "chain": [
            {
                "sequence": node.sequence, "from": node.from_party, "to": node.to_party,
                "type": node.transfer_type, "date": node.transfer_date,
                "ref": node.document_ref, "gap": node.gap_flag,
            }
            for node in chain
        ],
        "findings": [
            {
                "rule_ref": flag.rule_ref, "category": flag.category, "title": flag.title,
                "severity": flag.severity, "confidence": flag.confidence,
                "evidence": flag.evidence,
                "recommended_action": flag.recommended_action,
            }
            for flag in flags
        ],
    }


def rate(matched: int, total: int) -> str:
    if total == 0:
        return "n/a"
    return f"{matched}/{total} ({100.0 * matched / total:.1f}%)"


def write_report(rows: list[dict], out_path: Path, cases_dir: Path, engines: tuple[str, str, str],
                 fake: bool, failures: int) -> None:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    error_rows = [row for row in rows if row["expected"]]
    control_rows = [row for row in rows if not row["expected"]]
    detected = sum(1 for row in error_rows if row["detected"])
    clean = sum(1 for row in control_rows if row["detected"])
    verdict_rows = [row for row in rows if row["verdict_ok"] is not None]
    verdict_ok = sum(1 for row in verdict_rows if row["verdict_ok"])

    families = [
        ("Cross-document (matrix)", "MATCH-"),
        ("Ownership chain", "MH-CHAIN-"),
        ("Rule pack (charge/succession/litigation/land/identity/integrity)", "MH-"),
    ]

    lines: list[str] = []
    lines.append("# Phase 3 — AC-3 seeded-error detection report")
    lines.append("")
    lines.append(f"- Generated: {now}")
    lines.append(f"- Cases: `{cases_dir}` ({len(rows)} cases, "
                 f"{sum(len(row['observed']) for row in rows)} findings total)")
    lines.append(f"- Engines: ocr=`{engines[0]}`, classifier=`{engines[1]}`, nlp=`{engines[2]}`, "
                 "validator=`matrix-v1`, ownership=`evidence-v1`, rules=`mh-v1`")
    if fake:
        lines.append("- **--fake smoke run: detection numbers do not measure the real pipeline.**")
    if failures:
        lines.append(f"- **{failures} case(s) errored while running the pipeline.**")
    lines.append("")
    lines.append("## Headline")
    lines.append("")
    lines.append(f"- AC-3 seeded-error detection: **{rate(detected, len(error_rows))}** "
                 f"(target ≥{TARGET_RATE:.0%})")
    lines.append(f"- Control cases without a seeded error: {rate(clean, len(control_rows))} clean "
                 "(any finding would be a false positive)")
    if verdict_rows:
        lines.append(f"- Verdict matching the expectation where pinned: "
                     f"{rate(verdict_ok, len(verdict_rows))}")
    lines.append("")
    lines.append("## By error family")
    lines.append("")
    lines.append("| family | cases | detected |")
    lines.append("|---|---|---|")
    for label, prefix in families:
        if label.startswith("Rule pack"):
            group = [row for row in error_rows
                     if any(ref.startswith("MH-") for ref in row["expected"])
                     and not any(ref.startswith("MH-CHAIN-") for ref in row["expected"])]
        else:
            group = [row for row in error_rows
                     if any(ref.startswith(prefix) for ref in row["expected"])]
        if group:
            lines.append(f"| {label} | {len(group)} | "
                         f"{rate(sum(1 for row in group if row['detected']), len(group))} |")
    lines.append("")
    lines.append("## Per case")
    lines.append("")
    for row in rows:
        mark = "✅" if row["detected"] else "❌"
        lines.append(f"### {mark} `{row['name']}`")
        lines.append("")
        lines.append(f"- Seeded error: {row['injected']} ({row['language']})")
        expected = ", ".join(f"`{ref}`" for ref in row["expected"]) or "— (control)"
        observed = ", ".join(f"`{ref}`" for ref in row["observed"]) or "—"
        lines.append(f"- Expected: {expected}; observed: {observed}")
        if row["missing"]:
            lines.append(f"- **Missing: {', '.join(row['missing'])}**")
        lines.append(f"- Verdict: `{row['verdict']}`"
                     + (f" (expected `{row['verdict_expected']}`)" if row["verdict_expected"] else ""))
        for reason in row["reasons"]:
            lines.append(f"  - reason: {reason}")
        if row["chain"]:
            steps = "; ".join(
                f"{node['sequence']}. {node['from'] or 'unknown'} → {node['to']}"
                f" [{node['type']}{', GAP' if node['gap'] else ''}]"
                for node in row["chain"]
            )
            lines.append(f"- Ownership chain: {steps}")
        for finding in row["findings"]:
            evidence = (finding["evidence"] or "").replace("\n", " ")
            lines.append(f"- Finding `{finding['rule_ref']}` ({finding['severity']}, "
                         f"conf {finding['confidence']}): {finding['title']} — {evidence}")
        lines.append("")

    lines.append("## Limitations (honest list)")
    lines.append("")
    lines.append("- The corpus is generated as digital text-layer PDFs: extraction accuracy on")
    lines.append("  scanned/Marathi documents is measured separately by the AC-2 report. AC-3")
    lines.append("  measures the consistency/ownership/rule/verdict logic on top of the pipeline.")
    lines.append("- Fixture wording and the pattern pack share label conventions (documented in")
    lines.append("  ``scripts/make_fixtures.py``); the independent AC dataset is Phase 10 work.")
    lines.append("- The hash-tamper case flips the stored verification result at the metadata")
    lines.append("  level (as if ``/blockchain/verify`` had reported MISMATCH); producing that state")
    lines.append("  from a real on-chain record is Phase 5 work.")
    lines.append("- Findings are screening indicators for a reviewer, not legal determinations")
    lines.append("  (Conflict-Handling rule, master plan 1.4).")
    lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    json_path = out_path.with_suffix(".json")
    json_path.write_text(
        json.dumps({"generated": now, "fake": fake, "rows": rows}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"report: {out_path}")
    print(f"data:   {json_path}")


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    args = parse_args(argv)

    if args.fake:
        os.environ["OCR_ENGINE"] = "fake"
        os.environ["DOC_CLASSIFIER_ENGINE"] = "fake"
        os.environ["NLP_EXTRACTOR_ENGINE"] = "fake"

    # Imported after engine selection so --fake wins over backend/.env.
    from app.services.analysis_engine import _extracted_blob
    from app.services.cross_validate import MatrixCrossValidator
    from app.services.ownership_evidence import EvidenceOwnershipBuilder
    from app.services.registry import get_doc_classifier, get_nlp_extractor, get_ocr_service
    from app.services.rules_mh import MaharashtraRuleEngine
    from app.services.verdict import derive_verdict

    cases_dir = Path(args.cases)
    manifest_path = cases_dir / "_cases.json"
    if not manifest_path.exists():
        print(f"manifest not found: {manifest_path}\n"
              f"run: .venv\\Scripts\\python.exe scripts\\make_error_set.py", file=sys.stderr)
        return 2
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if args.limit:
        manifest = manifest[: args.limit]

    ocr_service = get_ocr_service()
    classifier = get_doc_classifier()
    extractor = get_nlp_extractor()
    engines = (ocr_service.engine_version, classifier.engine_version, extractor.engine_version)
    print(f"engines: {engines[0]} | {engines[1]} | {engines[2]}")

    rows: list[dict] = []
    failures = 0
    for number, entry in enumerate(manifest, start=1):
        case_dir = cases_dir / entry["name"]
        try:
            row = run_case(entry, case_dir, ocr_service, classifier, extractor,
                           MatrixCrossValidator(), EvidenceOwnershipBuilder(),
                           MaharashtraRuleEngine(), derive_verdict, _extracted_blob)
        except Exception as exc:  # keep scoring the remaining cases
            failures += 1
            print(f"  [{number:2}] {entry['name']:34} ERROR: {exc}")
            continue
        rows.append(row)
        mark = "DETECTED" if row["detected"] else "MISSED  "
        print(f"  [{number:2}] {entry['name']:34} {mark}  verdict={row['verdict']:<12} "
              f"refs={','.join(row['observed']) or '-'}")

    if not rows:
        print("no cases scored", file=sys.stderr)
        return 1

    error_rows = [row for row in rows if row["expected"]]
    control_rows = [row for row in rows if not row["expected"]]
    detected = sum(1 for row in error_rows if row["detected"])
    print(f"\nAC-3 detection: {rate(detected, len(error_rows))}  "
          f"controls clean: {rate(sum(1 for row in control_rows if row['detected']), len(control_rows))}")
    if failures:
        print(f"case errors: {failures}")

    write_report(rows, Path(args.out), cases_dir, engines, args.fake, failures)
    if failures or detected < len(error_rows):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
